def arr_sha(a: np.ndarray) -> str:
    return hashlib.sha256(np.ascontiguousarray(a).tobytes()).hexdigest()


def ndarray_state_hash(obj) -> str:
    h = hashlib.sha256()
    for k in sorted(vars(obj)):
        v = getattr(obj, k)
        if isinstance(v, np.ndarray):
            a = np.ascontiguousarray(v)
            h.update(k.encode())
            h.update(str(a.shape).encode())
            h.update(str(a.dtype).encode())
            h.update(a.tobytes())
    return h.hexdigest()


def clone_rng(state):
    rng = np.random.default_rng()
    rng.bit_generator.state = copy.deepcopy(state)
    return rng


def model_dict(s):
    out = {}
    for k in MODEL_KEYS:
        v = getattr(s, k)
        out[k] = np.array(v, copy=True) if isinstance(v, np.ndarray) else v
    return out


def inverse_cdf_rows(p, u):
    c = np.cumsum(np.asarray(p, dtype=np.float64), axis=1)
    c[:, -1] = 1.0
    z = np.sum(c < np.asarray(u, dtype=np.float64)[:, None], axis=1)
    return np.minimum(z, p.shape[1] - 1).astype(np.int64)


def predict_round(pred, cur, tok, pos, masked):
    xn, xraw = context_from_arr_unconditional(np.asarray(cur, dtype=np.int64), tok, pos)
    pred.rebuild(xn)
    probs = np.empty((len(masked), V), dtype=np.float64)
    for qi, t0 in enumerate(masked):
        t = int(t0)
        a, q, num, den = pred._read(t)
        _u, _h, _rf, p = pred._tail(a, np.asarray(xraw[t], dtype=np.float64))
        probs[qi] = np.asarray(p, dtype=np.float64)
    probs /= probs.sum(axis=1, keepdims=True)
    return probs


def reconstruct_r6b3(source, tokens, indices, rng_state, tok0, pos0):
    b = pickle.loads(pickle.dumps(source, pickle.HIGHEST_PROTOCOL))
    rng = clone_rng(rng_state)
    ones = np.ones(b.c.V, dtype=np.float64)
    stream = hashlib.sha256()
    for j, image_index in enumerate(indices, start=1):
        truth = np.asarray(tokens[int(image_index)], dtype=np.int64)
        sm = sample_mask_set(b.c.N, rng)
        masked = np.asarray(sm.masked_positions, dtype=np.int64)
        arr = truth.copy(); arr[masked] = core.MASK
        mirror_seed = int(rng.integers(1, 2**31 - 1))
        core.seed_numba(mirror_seed)
        xn, xraw = context_from_arr_unconditional(arr, tok0, pos0)
        b.learn_mask_batch(xn, xraw, masked, truth, ones, rng)
        stream.update(masked.tobytes())
        stream.update(np.asarray([mirror_seed], dtype=np.int64).tobytes())
        if j in (256, 512, 1024):
            print("A0_RECON_PROGRESS", json.dumps({"context": j}), flush=True)
    return b, stream.hexdigest(), rng.bit_generator.state


def reference_trace_gate(system, tok, pos, schedules):
    model = model_dict(system)
    max_conf_err = 0.0
    mask_exact = True
    image_count_ok = True
    for i, tr_image in enumerate(schedules):
        pred = core.P3ImageSystem(system.c, model, BASE_GEN_SEED + 100000 + i)
        cur = np.full(system.c.N, MASK, dtype=np.int64)
        for r in range(ROUNDS):
            tr = tr_image[r]
            masked = np.asarray(tr['masked_positions_before'], dtype=np.int64)
            remask = np.asarray(tr['remasked_positions'], dtype=np.int64)
            if not np.array_equal(masked, np.flatnonzero(cur == MASK)):
                mask_exact = False
            p = predict_round(pred, cur, tok, pos, masked)
            sampled = np.asarray(tr['sampled_ids'], dtype=np.int64)
            conf = np.asarray(tr['sampled_confidence'], dtype=np.float64)
            if len(masked):
                max_conf_err = max(max_conf_err, float(np.max(np.abs(p[np.arange(len(masked)), sampled] - conf))))
            proposal = cur.copy(); proposal[masked] = sampled
            cur = proposal; cur[remask] = MASK
        if pred.image_count != ROUNDS:
            image_count_ok = False
    return {
        "trace_mask_context_exact": bool(mask_exact),
        "reference_probability_confidence_max_abs_error": float(max_conf_err),
        "reference_probability_confidence_pass": bool(max_conf_err < 1e-7),
        "image_count_after_three_rounds_exact": bool(image_count_ok),
    }


def one_metrics(p, gt, sampled, cur):
    p = np.asarray(p, dtype=np.float64); gt = np.asarray(gt, dtype=np.int64)
    sampled = np.asarray(sampled, dtype=np.int64)
    truep = p[np.arange(len(gt)), gt]; ce = -np.log(np.clip(truep, 1e-12, 1.0))
    arg = np.argmax(p, axis=1); acc = arg == gt; is61 = gt == DOM; non = ~is61
    vis = np.asarray(cur) != MASK
    def m(x): return float(np.mean(x)) if np.size(x) else np.nan
    return {
        "ce": m(ce), "acc": m(acc),
        "ce_non61": m(ce[non]),
        "mean_p61": m(p[:, DOM]),
        "p61_on_non61": m(p[non, DOM]),
        "context61_fraction": m(np.asarray(cur)[vis] == DOM) if vis.any() else np.nan,
    }


def eval_causal(system, tok, pos, schedules, gt, shared_u):
    model = model_dict(system)
    rows = []
    gates = {
        "round1_probability_bitwise_parity": True,
        "round1_sample_exact_parity": True,
        "committed_position_parity": True,
        "intervention_purity": True,
        "common_random_number_integrity": True,
        "image_count_after_three_rounds_exact": True,
    }
    for i in range(len(gt)):
        ps = core.P3ImageSystem(system.c, model, BASE_GEN_SEED + 100000 + i)
        pt = core.P3ImageSystem(system.c, model, BASE_GEN_SEED + 100000 + i)
        cs = np.full(system.c.N, MASK, dtype=np.int64)
        ct = np.full(system.c.N, MASK, dtype=np.int64)
        self_metrics = teacher_metrics = None
        for r in range(ROUNDS):
            tr = schedules[i][r]
            masked = np.asarray(tr['masked_positions_before'], dtype=np.int64)
            remask = np.asarray(tr['remasked_positions'], dtype=np.int64)
            if not np.array_equal(np.flatnonzero(cs == MASK), masked) or not np.array_equal(np.flatnonzero(ct == MASK), masked):
                gates['committed_position_parity'] = False
            if r == 0:
                if not np.array_equal(cs, ct) or not np.all(cs == MASK):
                    gates['intervention_purity'] = False
            else:
                if not np.array_equal(cs == MASK, ct == MASK):
                    gates['intervention_purity'] = False
                vis = np.flatnonzero(ct != MASK)
                if len(vis) and not np.array_equal(ct[vis], gt[i, vis]):
                    gates['intervention_purity'] = False
                if np.any((cs != ct) & (ct == MASK)):
                    gates['intervention_purity'] = False
            p1 = predict_round(ps, cs, tok, pos, masked)
            p2 = predict_round(pt, ct, tok, pos, masked)
            u = np.asarray(shared_u[i, r, masked], dtype=np.float64)
            if not np.array_equal(u, shared_u[i, r, masked]):
                gates['common_random_number_integrity'] = False
            z1 = inverse_cdf_rows(p1, u); z2 = inverse_cdf_rows(p2, u)
            if r == 0 and not np.array_equal(p1, p2): gates['round1_probability_bitwise_parity'] = False
            if r == 0 and not np.array_equal(z1, z2): gates['round1_sample_exact_parity'] = False
            if r == ROUNDS - 1:
                self_metrics = one_metrics(p1, gt[i, masked], z1, cs)
                teacher_metrics = one_metrics(p2, gt[i, masked], z2, ct)
            prop_s = cs.copy(); prop_s[masked] = z1
            prop_t = ct.copy(); prop_t[masked] = z2
            cs_next = prop_s.copy(); cs_next[remask] = MASK
            ct_next = ct.copy(); newly = np.setdiff1d(masked, remask, assume_unique=True)
            ct_next[newly] = gt[i, newly]; ct_next[remask] = MASK
            oldvis = np.flatnonzero(ct != MASK)
            if len(oldvis): ct_next[oldvis] = gt[i, oldvis]
            cs, ct = cs_next, ct_next
        if ps.image_count != ROUNDS or pt.image_count != ROUNDS:
            gates['image_count_after_three_rounds_exact'] = False
        rows.append({
            "CE": self_metrics['ce'] - teacher_metrics['ce'],
            "D_non61": self_metrics['ce_non61'] - teacher_metrics['ce_non61'],
            "F61": self_metrics['p61_on_non61'] - teacher_metrics['p61_on_non61'],
            "C61": self_metrics['context61_fraction'] - teacher_metrics['context61_fraction'],
            "delta_P61": self_metrics['mean_p61'] - teacher_metrics['mean_p61'],
        })
    gates['all_pass'] = bool(all(gates.values()))
    summary = {k: float(np.nanmean([r[k] for r in rows])) for k in EXPECTED['effects']}
    return summary, gates


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--data', type=Path, required=True)
    ap.add_argument('--tokenizer', type=Path, required=True)
    ap.add_argument('--checkpoint', type=Path, required=True)
    ap.add_argument('--effectiveness', type=Path, required=True,
                    help='Directory containing exact historical R6B4 effectiveness result/ traces')
    ap.add_argument('--out', type=Path, required=True)
    ap.add_argument('--threads', type=int, default=4)
    a = ap.parse_args(); a.out.mkdir(parents=True, exist_ok=True)

    random.seed(7311); np.random.seed(7311); torch.manual_seed(7311); torch.set_num_threads(a.threads)
    device = torch.device('cpu')

    source, meta, train_rng, schedule = trainer.load_full_checkpoint(a.checkpoint)
    if abs(float(meta.get('context_epoch_equivalent', -1.0)) - 2.0) > 1e-12:
        raise RuntimeError('not exact R6B3 2.0-epoch checkpoint')
    offset = int(schedule['offset'])
    indices = np.asarray(schedule['permutation'], dtype=np.int64)[offset:offset+1024]
    rng_state = copy.deepcopy(train_rng.bit_generator.state)

    xall, yall, _xte, _yte = core.load(a.data)
    x012, y012 = core.subset012(xall, yall)
    xtr, _ytr, xva, _yva = core.split(x012, y012, .1, 7)
    tokenizer, tok_meta = base.load_frozen_tokenizer(a.tokenizer, device)
    tr, _sptr = base.encode_snn(tokenizer, xtr, device, 256)
    va, _spva = base.encode_snn(tokenizer, xva, device, 256)
    tok0, pos0, _input_audit = build_input_embeddings(tokenizer, source.c.D, grid=7)

    validation_ids = np.random.default_rng(SELECTION_SEED).choice(len(va), size=N_IMAGES, replace=False).astype(np.int64)
    gt = np.asarray(va[validation_ids], dtype=np.int16)
    shared_uniform = np.random.default_rng(UNIFORM_SEED).random((N_IMAGES, ROUNDS, source.c.N))
    shared_gumbel = np.random.default_rng(GUMBEL_SEED).gumbel(size=(N_IMAGES, ROUNDS, source.c.N))

    provenance = {
        "validation_pool": int(len(va)),
        "selection_seed": SELECTION_SEED,
        "uniform_seed": UNIFORM_SEED,
        "gumbel_seed": GUMBEL_SEED,
        "validation_ids_sha256": arr_sha(validation_ids),
        "gt_tokens_sha256": arr_sha(gt),
        "shared_uniform_sha256": arr_sha(shared_uniform),
        "shared_gumbel_sha256": arr_sha(shared_gumbel),
    }
    provenance['hash_pass'] = bool(
        provenance['validation_ids_sha256'] == EXPECTED['validation_ids_sha256'] and
        provenance['gt_tokens_sha256'] == EXPECTED['gt_tokens_sha256'] and
        provenance['shared_uniform_sha256'] == EXPECTED['shared_uniform_sha256'] and
        provenance['shared_gumbel_sha256'] == EXPECTED['shared_gumbel_sha256'])
    print('D3E_A0_SHARED_PROVENANCE', json.dumps(provenance, indent=2), flush=True)
    if not provenance['hash_pass']:
        raise RuntimeError('historical Gate-A shared-input provenance mismatch')

    terminal, stream_sha, _rng_after = reconstruct_r6b3(source, tr, indices, rng_state, tok0, pos0)
    terminal_hash = ndarray_state_hash(terminal)
    state_pass = terminal_hash == EXPECTED['r6b3_terminal_ndarray_state_sha256']
    print('D3E_A0_TERMINAL_STATE', json.dumps({"sha256": terminal_hash, "pass": state_pass}, indent=2), flush=True)
    if not state_pass:
        raise RuntimeError('historical R6B3+1024 terminal state mismatch')

    trace_path = a.effectiveness / 'result' / 'r6b3_frozen_new_params_r3_t8_traces.json'
    if not trace_path.exists():
        # Allow actions/download-artifact extraction directly into the supplied directory.
        alt = a.effectiveness / 'r6b3_frozen_new_params_r3_t8_traces.json'
        if alt.exists(): trace_path = alt
    schedules = json.loads(trace_path.read_text(encoding='utf-8'))
    if len(schedules) < N_IMAGES:
        raise RuntimeError('historical effectiveness trace has fewer than 256 images')
    schedules = schedules[:N_IMAGES]

    ref_gate = reference_trace_gate(terminal, tok0, pos0, schedules)
    print('D3E_A0_REFERENCE_TRACE_GATE', json.dumps(ref_gate, indent=2), flush=True)
    if not (ref_gate['trace_mask_context_exact'] and ref_gate['reference_probability_confidence_pass'] and ref_gate['image_count_after_three_rounds_exact']):
        raise RuntimeError('historical trace/reference predictor reconstruction failed')

    summary, causal_gates = eval_causal(terminal, tok0, pos0, schedules, gt.astype(np.int64), shared_uniform)
    diffs = {k: abs(summary[k] - EXPECTED['effects'][k]) for k in EXPECTED['effects']}
    pass_effect = max(diffs.values()) < TOL
    result = {
        "stage": "D3E_A0_GATE_A_PROVENANCE_RECOVERY",
        "pass": bool(provenance['hash_pass'] and state_pass and causal_gates['all_pass'] and pass_effect),
        "provenance": provenance,
        "terminal_state": {
            "ndarray_state_sha256": terminal_hash,
            "expected": EXPECTED['r6b3_terminal_ndarray_state_sha256'],
            "pass": state_pass,
            "training_stream_sha256": stream_sha,
        },
        "reference_trace_gate": ref_gate,
        "causal_replay_gates": causal_gates,
        "reconstructed_effects": summary,
        "expected_effects": EXPECTED['effects'],
        "abs_diff": diffs,
        "tolerance": TOL,
        "critical_boundary": (
            "Historical Gate-A trace supplies position/remask schedules; causal proposal contents are resampled "
            "with the independent CRN field default_rng(9917311).random((256,3,49)). "
            "Do not require causal replay sampled IDs to equal historical reference-trace sampled IDs."
        ),
    }
    (a.out / 'D3E_A0_PROVENANCE.json').write_text(json.dumps(result, indent=2), encoding='utf-8')
    np.savez_compressed(a.out / 'D3E_A0_SHARED_INPUTS.npz',
                        validation_ids=validation_ids, gt_tokens=gt,
                        shared_uniform=shared_uniform, shared_gumbel=shared_gumbel)
    print('D3E_A0_COMPLETE', json.dumps({"pass": result['pass'], "abs_diff": diffs}, indent=2), flush=True)
    if not result['pass']:
        raise RuntimeError('D3E-A0 failed authoritative Gate-A provenance/control reproduction')


if __name__ == '__main__':
    main()
