#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
U4 — sparse tail gate for the unified SNN-Transform project.

Purpose
-------
Test whether the dense tail after the already-validated attention core can be
replaced by a structurally sparse output projection and structurally/activity-
sparse FFN without changing the task definition.

This is intentionally a cloud functional/compute gate, not a SpiNNaker timing
claim. Sparse masks correspond to connections that would not exist on hardware;
we therefore count only masked-in synapses and only active hidden fan-out.

Reference tail:
    z = x @ W_o
    h = GELU(z @ W_1 + b_1)
    y = h @ W_2 + b_2

Candidate tail:
    z = x @ (M_o * W_o)
    u = z @ (M_1 * W_1) + b_1
    h = GELU(u) * gate(u)
    y = h @ (M_2 * W_2) + b_2

Masks are fixed random balanced masks. Candidate is trained from scratch on a
teacher generated by the dense reference. This asks an architecture question:
can a sparse realization learn the same mapping? It does NOT claim that an
arbitrary trained dense matrix can be sparsified with exact equality.
"""

import argparse
import json
import math
import os
import random
from dataclasses import dataclass

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F


def set_seed(seed: int):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)


def rel_l2(a: torch.Tensor, b: torch.Tensor, eps=1e-12):
    return float((a-b).norm() / (b.norm()+eps))


def cosine(a: torch.Tensor, b: torch.Tensor):
    a=a.reshape(a.shape[0], -1)
    b=b.reshape(b.shape[0], -1)
    return float(F.cosine_similarity(a,b,dim=1).mean())


def balanced_mask(n_in: int, n_out: int, density: float, device=None):
    """Create a fixed mask with near-equal fan-in per output column."""
    k=max(1, min(n_in, int(round(density*n_in))))
    m=torch.zeros(n_in,n_out,device=device)
    for j in range(n_out):
        idx=torch.randperm(n_in,device=device)[:k]
        m[idx,j]=1.0
    return m


class DenseTail(nn.Module):
    def __init__(self,d,ff):
        super().__init__()
        self.wo=nn.Linear(d,d,bias=False)
        self.w1=nn.Linear(d,ff)
        self.w2=nn.Linear(ff,d)
    def forward(self,x):
        z=self.wo(x)
        u=self.w1(z)
        h=F.gelu(u)
        y=self.w2(h)
        return y,{"z":z,"u":u,"h":h}


class SparseLinear(nn.Module):
    def __init__(self,n_in,n_out,density,bias=True):
        super().__init__()
        self.weight=nn.Parameter(torch.empty(n_out,n_in))
        self.bias=nn.Parameter(torch.zeros(n_out)) if bias else None
        mask=balanced_mask(n_in,n_out,density).T.contiguous()
        self.register_buffer("mask",mask)
        nn.init.kaiming_uniform_(self.weight,a=math.sqrt(5))
    def forward(self,x):
        return F.linear(x,self.weight*self.mask,self.bias)
    @property
    def density(self):
        return float(self.mask.mean())
    @property
    def nnz(self):
        return int(self.mask.sum().item())


class SparseTail(nn.Module):
    def __init__(self,d,ff,d_out,d_ff,gate_target=0.25,gate_temp=0.10):
        super().__init__()
        self.wo=SparseLinear(d,d,d_out,bias=False)
        self.w1=SparseLinear(d,ff,d_ff,bias=True)
        self.w2=SparseLinear(ff,d,d_ff,bias=True)
        self.log_theta=nn.Parameter(torch.zeros(ff))
        self.gate_target=gate_target
        self.gate_temp=gate_temp
    def forward(self,x,hard=False):
        z=self.wo(x)
        u=self.w1(z)
        theta=self.log_theta
        if hard:
            gate=(u>theta).to(u.dtype)
        else:
            gate=torch.sigmoid((u-theta)/self.gate_temp)
        h=F.gelu(u)*gate
        y=self.w2(h)
        return y,{"z":z,"u":u,"h":h,"gate":gate}


@dataclass
class CandidateResult:
    out_density: float
    ff_density: float
    target_activity: float
    rel_l2: float
    cosine: float
    activity: float
    static_synapse_fraction: float
    effective_synop_fraction: float
    pass_gate: bool


def sample_x(batch,tokens,d,device):
    # Mixed distribution avoids overfitting to one Gaussian scale and roughly
    # mimics normalized hidden states plus occasional larger features.
    x=torch.randn(batch,tokens,d,device=device)
    scale=torch.exp(0.25*torch.randn(batch,1,1,device=device))
    return x*scale


def train_candidate(teacher,cand,args,device):
    opt=torch.optim.AdamW(cand.parameters(),lr=args.lr,weight_decay=1e-4)
    for step in range(1,args.steps+1):
        x=sample_x(args.batch,args.tokens,args.d,device)
        with torch.no_grad():
            target,_=teacher(x)
        pred,st=cand(x,hard=False)
        task=F.mse_loss(pred,target)
        activity=st["gate"].mean()
        sparsity_penalty=(activity-args.target_activity).pow(2)
        loss=task+args.activity_lambda*sparsity_penalty
        opt.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(cand.parameters(),1.0)
        opt.step()
        if step==1 or step%args.report_every==0:
            print("TRAIN",json.dumps({
                "step":step,"loss":float(loss.detach()),"mse":float(task.detach()),
                "soft_activity":float(activity.detach())
            }))


def eval_candidate(teacher,cand,args,device):
    rs=[];cs=[];acts=[]
    with torch.no_grad():
        for _ in range(args.eval_batches):
            x=sample_x(args.eval_batch,args.tokens,args.d,device)
            target,_=teacher(x)
            pred,st=cand(x,hard=True)
            rs.append(rel_l2(pred,target));cs.append(cosine(pred,target));acts.append(float(st["gate"].mean()))
    r=float(np.mean(rs));c=float(np.mean(cs));a=float(np.mean(acts))

    d=args.d;ff=args.ff
    dense_syn=d*d + d*ff + ff*d
    static=cand.wo.nnz+cand.w1.nnz+cand.w2.nnz
    # For W2 only active hidden units emit; Wo/W1 still process all channels.
    eff=cand.wo.nnz+cand.w1.nnz+a*cand.w2.nnz
    static_frac=static/dense_syn
    eff_frac=eff/dense_syn
    return r,c,a,static_frac,eff_frac


def main():
    p=argparse.ArgumentParser()
    p.add_argument('--out',default='unified_snn_transform/run/U4')
    p.add_argument('--seed',type=int,default=41)
    p.add_argument('--tokens',type=int,default=16)
    p.add_argument('--d',type=int,default=32)
    p.add_argument('--ff',type=int,default=64)
    p.add_argument('--steps',type=int,default=900)
    p.add_argument('--batch',type=int,default=256)
    p.add_argument('--eval-batches',type=int,default=8)
    p.add_argument('--eval-batch',type=int,default=256)
    p.add_argument('--lr',type=float,default=2e-3)
    p.add_argument('--activity-lambda',type=float,default=0.05)
    p.add_argument('--target-activity',type=float,default=0.25)
    p.add_argument('--report-every',type=int,default=300)
    p.add_argument('--rel-gate',type=float,default=0.08)
    p.add_argument('--cos-gate',type=float,default=0.995)
    p.add_argument('--eff-gate',type=float,default=0.45)
    p.add_argument('--threads',type=int,default=4)
    args=p.parse_args()

    torch.set_num_threads(args.threads)
    set_seed(args.seed)
    device=torch.device('cpu')
    os.makedirs(args.out,exist_ok=True)

    teacher=DenseTail(args.d,args.ff).to(device)
    teacher.eval()
    for p0 in teacher.parameters(): p0.requires_grad_(False)

    grid=[
        (0.50,0.50,0.50),
        (0.50,0.25,0.50),
        (0.50,0.25,0.25),
        (0.25,0.50,0.50),
        (0.25,0.25,0.50),
        (0.25,0.25,0.25),
        (0.125,0.25,0.25),
    ]
    rows=[]
    best=None
    for i,(do,d1,d2) in enumerate(grid):
        set_seed(args.seed+100+i)
        cand=SparseTail(args.d,args.ff,do,d1,gate_target=args.target_activity).to(device)
        train_candidate(teacher,cand,args,device)
        r,c,a,sf,ef=eval_candidate(teacher,cand,args,device)
        ok=(r<=args.rel_gate and c>=args.cos_gate and ef<=args.eff_gate)
        row={
            "output_density":do,"ff1_density":d1,"ff2_density":d2,
            "hard_hidden_activity":a,"rel_l2":r,"cosine":c,
            "static_synapse_fraction":sf,"effective_synop_fraction":ef,
            "effective_synop_reduction":1.0-ef,"PASS":ok
        }
        rows.append(row)
        print("CAND",json.dumps(row))
        score=(0 if ok else 1000)+r+0.05*ef
        if best is None or score<best[0]: best=(score,row,cand)

    # Conservative promotion gate: at least one candidate must preserve the
    # teacher mapping while cutting effective work by >=55%.
    passing=[r for r in rows if r['PASS']]
    result={
        "stage":"UNIFIED_U4_SPARSE_TAIL",
        "config":vars(args),
        "reference":"dense output projection + dense GELU FFN",
        "candidate":"fixed structural sparse output/FFN + thresholded hidden activity",
        "rows":rows,
        "best_passing":min(passing,key=lambda r:(r['effective_synop_fraction'],r['rel_l2'])) if passing else None,
        "gates":{
            "at_least_one_candidate_passes":bool(passing),
            "functional_rel_l2_gate":args.rel_gate,
            "functional_cosine_gate":args.cos_gate,
            "effective_synop_fraction_gate":args.eff_gate
        },
        "PASS":bool(passing),
        "decision":(
            "promote sparse tail principle; next integrate with trained unified block"
            if passing else
            "do not promote yet; adjust sparse topology/training before block integration"
        )
    }
    with open(os.path.join(args.out,'U4_RESULTS.json'),'w') as f: json.dump(result,f,indent=2)
    print(json.dumps(result,indent=2))

if __name__=='__main__':
    main()
